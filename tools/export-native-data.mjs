// Export resolved browser properties plus explicitly native-only material rows.
import { C } from './test-support.mjs';
import { LIQ, VISC_TEMP } from '../js/liquids.js';
import { LCAP, BCAP, AIR_CAP } from '../js/matter.js';
import { REACT, SWAP } from '../js/reactions.js';
import { CLEAR } from '../js/render/liquids.js';
import { PAL, SKY_STOPS, WALL, SEASON_GRASS, GRASS_OUT } from '../js/render/terrain.js';
import { HILLS } from '../js/render/backdrop.js';
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
const nativeFluids = JSON.parse(readFileSync('godot/data/native_fluids.json', 'utf8')).fluids;
// Clone first: browser reference objects and IDs are never changed by the export.
const nativeLiquids = LIQ.slice();
for (const f of nativeFluids) {
  const [r,g,b] = f.rgb;
  nativeLiquids[f.id] = { grav:1, visc:f.viscosity, minSpread:3, minDiff:2, dens:f.density,
    gas:false, br:r,bg:g,bb:b,ba:f.opacity, sr:Math.min(255,r+30),sg:Math.min(255,g+30),sb:Math.min(255,b+30),sa:Math.min(1,f.opacity+.2),
    dr:Math.round(r*.55),dg:Math.round(g*.55),db:Math.round(b*.55),da:Math.min(1,f.opacity+.2),paintT:20,flow:f.flow };
}
const fluidRows = Array.from({ length: C.NLIQ }, (_, i) => {
  const f = nativeLiquids[i];
  const cap = nativeFluids.find(row => row.id === i)?.capacity ?? LCAP[i];
  return f ? `{${f.grav},${f.visc},${f.minSpread},${f.minDiff},${f.dens},${cap},${!!f.gas},${f.br},${f.bg},${f.bb},${f.paintT}}` : '{}';
});
const rules = [];
for (const [type, rows] of Object.entries(VISC_TEMP)) for (const [limit, cadence] of rows)
  rules.push(`{${type},${Number.isFinite(limit) ? limit : 'std::numeric_limits<double>::infinity()'},${cadence}}`);
const pairs = [];
for (let i = 0; i < REACT.length; i++) if (REACT[i] === SWAP) pairs.push(i);
for (const f of nativeFluids) for (let t=1;t<C.NLIQ;t++) if(t!==f.id && nativeLiquids[t]) {
  pairs.push(f.id*C.NLIQ+t,t*C.NLIQ+f.id);
}
const constants = ['W', 'H', 'CHUNK', 'NSOL', 'NLIQ', 'WATER', 'OIL', 'FOAM', 'STORM', 'SOL_SALT', 'SOL_SUGAR', 'SOL_SILT', 'SOL_METAL'];
const source = `// Generated by node tools/export-native-data.mjs. Do not tune this copy.\n#pragma once\n#include <array>\n#include <limits>\nnamespace ecologist {\n${constants.map(n => `inline constexpr int ${n} = ${C[n]};`).join('\n')}\ninline constexpr double AIR_CAP = ${AIR_CAP}, SALT_CAP = ${BCAP[C.SALT]}, SUGAR_CAP = ${BCAP[C.SUGAR]};\nstruct Fluid { int gravity=0, viscosity=1, min_spread=0, min_diff=0; double density=0, capacity=0; bool gas=false; int r=0,g=0,b=0; double paint_temperature=20; };\ninline constexpr std::array<Fluid,NLIQ> FLUIDS = {{\n${fluidRows.join(',\n')}\n}};\nstruct Viscosity { int type; double limit; int cadence; };\ninline constexpr Viscosity VISCOSITIES[] = {${rules.join(',')}};\ninline constexpr auto SWAPS = [] { std::array<bool,NLIQ*NLIQ> a{}; for (int i : {${pairs.join(',')}}) a[i]=true; return a; }();\n}\n`;
mkdirSync('native/generated', { recursive: true });
const target = 'native/generated/materials.hpp';
if (!existsSync(target) || readFileSync(target, 'utf8') !== source) writeFileSync(target, source);
console.log(`Exported ${LIQ.length - 1} browser and ${nativeFluids.length} native fluids, ${C.NSOL} channels and ${pairs.length} swap entries.`);
// The GPU uses the very same palettes/opacity/flow values as the HTML renderer.
const decimal = n => Number.isInteger(n) ? `${n}.0` : String(n);
const packed = c => [c & 255, (c >>> 8) & 255, (c >>> 16) & 255];
const vector = values => `vec${values.length}(${values.map(decimal).join(',')})`;
const color = c => vector(c.map(n => n / 255));
const array = (type,name,values) => `const ${type} ${name}[${values.length}] = ${type}[${values.length}](${values.join(',\n')});\n`;
let visual = '// Generated from the HTML renderer by tools/export-native-data.mjs.\n';
for (const [name,prefix] of [['SURFACE','s'],['BODY','b'],['DEEP','d']]) {
  visual += array('vec4', `LIQ_${name}`, Array.from({length:C.NLIQ}, (_,i) => {
    const f=nativeLiquids[i];return vector(f ? [f[`${prefix}r`]/255,f[`${prefix}g`]/255,f[`${prefix}b`]/255,f[`${prefix}a`]] : [0,0,0,0]);
  }));
}
visual += array('vec4','LIQ_PARAMS',Array.from({length:C.NLIQ},(_,i)=>{const f=nativeLiquids[i];return vector(f ? [f.grav,f.flow,+!!f.gas,+CLEAR.has(i)] : [0,0,0,0]);}));
visual += array('vec3','SKY_COLORS',SKY_STOPS.map(color));
visual += array('vec3','CAVE_COLORS',WALL.map(c=>color(packed(c))));
visual += array('vec3','GRASS_COLORS',[...SEASON_GRASS[4],GRASS_OUT].map(c=>color(packed(c))));
for(const [name,id] of [['DIRT',C.DIRT],['STONE',C.STONE]]) {
  visual += array('vec3',`${name}_COLORS`,[...PAL[id].base,PAL[id].out,PAL[id].hl].map(c=>color(packed(c))));
}
visual += array('vec4','HILL_SHAPE',HILLS.map(h=>vector([h.f,h.top,h.rise,h.scale])));
visual += array('vec3','HILL_BODY',HILLS.map(h=>color(packed(h.body))));
visual += array('vec3','HILL_RIM',HILLS.map(h=>color(packed(h.rim))));
visual += array('int','HILL_SALT',HILLS.map(h=>String(h.salt)));
mkdirSync('godot/generated',{recursive:true});
const visualTarget='godot/generated/palettes.gdshaderinc';
if(!existsSync(visualTarget) || readFileSync(visualTarget,'utf8')!==visual) writeFileSync(visualTarget,visual);
process.exit(0);
